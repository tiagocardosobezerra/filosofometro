// Looks up a cover for every recommended book on Open Library and writes covers.js.
// Usage: node tests/make-covers.js   (about one request per second; writes tests/covers-report.md for review)
// Manual fixes go in OVERRIDE below: a cover id from openlibrary.org, or 0 for no cover.
// Covers already in covers.js are kept; only the missing ones are searched again (pass --all to redo everything).
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..");
const DATA = require(path.join(ROOT, "data.js"));
const S = require(path.join(ROOT, "support.js"));
const ALT = require(path.join(__dirname, "cover-titles.js"));

// Wrong matches found on review: studies or replies about the book instead of the book itself.
const OVERRIDE = { "kant/0": 0, "proudhon/1": 0, "heidegger/0": 0, "jean-paul-sartre/2": 0, "john-stuart-mill/1": 0, "yang-zhu/2": 0, "byung-chul-han/0": 0, "epicteto/0": 0, "parmenides/2": 0, "david-hume/0": 0, "jean-paul-sartre/1": 0, "karl-popper/1": 0, "gilles-deleuze/1": 0, "antonio-vieira/0": 0, "pascal/2": 0, "jurgen-habermas/1": 0, "herbert-marcuse/1": 0, "proudhon/2": 0, "dogen/1": 0 };

const norm = s => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9 ]/g, " ").replace(/\s+/g, " ").trim();
const STOP = new Set(["a", "o", "as", "os", "de", "da", "do", "das", "dos", "e", "em", "the", "of", "and", "sobre", "um", "uma", "para", "por", "com"]);
const words = s => norm(s).split(" ").filter(w => w && !STOP.has(w));
// Share of the title's words found in a candidate title.
const overlap = (want, got) => { const w = words(want), g = new Set(words(got)); return w.length ? w.filter(x => g.has(x)).length / w.length : 0; };
const sleep = ms => new Promise(r => setTimeout(r, ms));

async function search(q) {
  const url = `https://openlibrary.org/search.json?q=${encodeURIComponent(q)}&fields=title,author_name,cover_i&limit=10`;
  for (let tries = 0; tries < 4; tries++) {
    try {
      const res = await fetch(url, { headers: { "User-Agent": "Filosofometro/1.0 (book covers)" } });
      if (res.ok) return (await res.json()).docs || [];
      process.stdout.write(`[${res.status}]`);
    } catch (e) { process.stdout.write("[erro]"); }
    await sleep(10000 * (tries + 1));
  }
  return [];
}

async function cover(title, author) {
  const m = title.match(/^(.*?)\s*\((.*)\)$/);
  const t = m ? m[1] : title, by = m && !/em inglês|Os Pensadores/.test(m[2]) ? m[2] : author;
  for (const q of [`${t} ${by}`, t]) {
    const docs = await search(q);
    await sleep(1500);
    const byWords = words(by);
    const scored = docs.filter(d => d.cover_i).map(d => {
      const names = norm((d.author_name || []).join(" "));
      return { d, title: overlap(t, d.title), author: byWords.some(w => w.length > 3 && names.includes(w)) };
    }).filter(x => x.title >= 0.75 && (x.author || q !== t));
    let best = scored.find(x => x.author) || scored[0];
    // Search ranks the work itself first, often under its original title (L'étranger, Manifest der...).
    // Among the top three results, an edition by the same author with a cover is that work.
    if (!best && q !== t) {
      const top = docs.slice(0, 3).find(d => d.cover_i && byWords.some(w => w.length > 3 && norm((d.author_name || []).join(" ")).includes(w)));
      if (top) return { id: top.cover_i, got: `${top.title} | ${(top.author_name || []).slice(0, 2).join(", ")} (título diferente)`, author: true };
    }
    if (best) return { id: best.d.cover_i, got: `${best.d.title} | ${(best.d.author_name || []).slice(0, 2).join(", ")}`, author: best.author };
  }
  return { id: 0, got: "" };
}

(async () => {
  const people = [...DATA.PH, ...(DATA.BR || [])];
  const out = {}, rows = [], all = process.argv.includes("--all");
  let old = {};
  try { old = require(path.join(ROOT, "covers.js")); } catch (e) {}
  for (const p of people) {
    const books = [p.b, ...S.READING[p.id]];
    out[p.id] = [];
    for (const [i, b] of books.entries()) {
      const key = `${p.id}/${i}`;
      const alt = ALT[key], had = old[p.id] && old[p.id][i];
      let r;
      // A manual 0 marks a wrong match for the Portuguese title; the original title may still find the right book.
      if (key in OVERRIDE && (OVERRIDE[key] || !alt)) r = { id: OVERRIDE[key], got: "manual" };
      else if (!all && had) r = { id: had, got: "já encontrada", author: true };
      else {
        // The Portuguese title was already searched in an earlier run unless --all; then try the original title.
        r = all || !old[p.id] ? await cover(b, p.n) : { id: 0, got: "" };
        if (!r.id && alt) { r = await cover(...alt.split("|")); if (r.id) r.got += " (título original)"; }
      }
      out[p.id].push(r.id);
      rows.push(`| ${key} | ${b} | ${r.id || "**sem capa**"} | ${r.got}${r.id && !r.author && r.got !== "manual" ? " (autor não confere)" : ""} |`);
      process.stdout.write(r.id ? "." : "x");
    }
  }
  const js = `// Generated by tests/make-covers.js. Open Library cover ids for each thinker's three books (0 = no cover).\n(function(root){\nconst COVERS=${JSON.stringify(out).replace(/\],"/g, '],\n"')};\nif(typeof module!=="undefined")module.exports=COVERS;else root.AgoraCovers=COVERS;\n})(this);\n`;
  fs.writeFileSync(path.join(ROOT, "covers.js"), js);
  fs.writeFileSync(path.join(__dirname, "covers-report.md"), `# Capas\n\n| Livro | Título | Capa | Encontrado |\n|---|---|---|---|\n${rows.join("\n")}\n`);
  const found = Object.values(out).flat().filter(Boolean).length;
  console.log(`\n${found}/${rows.length} covers`);
})();
