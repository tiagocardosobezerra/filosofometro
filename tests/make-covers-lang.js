// Finds covers for the English and Spanish book lists, and refreshes chosen Portuguese ones.
// Usage:
//   node tests/make-covers-lang.js en            every English book (international and regional)
//   node tests/make-covers-lang.js es
//   node tests/make-covers-lang.js pt a/1,b/2    only these Portuguese slots, after their titles changed
// Same search as tests/make-covers.js (Open Library, title plus author, about one request per second).
// English and Spanish results go to covers.js as a per-language map: a cover id, 0 for none, or null to
// reuse the Portuguese cover. Without its own cover, a book reuses the Portuguese one only when it is the
// same work (listed in tests/covers-same.json); a different book shows the colored spine instead.
// Then run tests/fetch-covers.js to download the new images and tests/make-pages.js for the static pages.
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..");
const DATA = require(path.join(ROOT, "data.js"));
const S = require(path.join(ROOT, "support.js"));
const OLD = require(path.join(ROOT, "covers.js"));
const SAME = (() => { try { return require(path.join(__dirname, "covers-same.json")); } catch (e) { return {}; } })();

const norm = s => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9 ]/g, " ").replace(/\s+/g, " ").trim();
const STOP = new Set(["a", "o", "as", "os", "de", "da", "do", "das", "dos", "e", "em", "the", "of", "and", "sobre", "um", "uma", "para", "por", "com", "el", "la", "los", "las", "y", "del", "en", "un", "una", "on", "an", "to", "with", "con"]);
const words = s => norm(s).split(" ").filter(w => w && !STOP.has(w));
const overlap = (want, got) => { const w = words(want), g = new Set(words(got)); return w.length ? w.filter(x => g.has(x)).length / w.length : 0; };
const sleep = ms => new Promise(r => setTimeout(r, ms));
// Notes in parentheses that are not an author: language notes and series names.
const NOT_AUTHOR = /ingl[eê]s|English|portugu[eé]s|Portuguese|Os Pensadores/i;

async function search(q) {
  const url = `https://openlibrary.org/search.json?q=${encodeURIComponent(q)}&fields=title,author_name,cover_i&limit=10`;
  for (let tries = 0; tries < 4; tries++) {
    try {
      const res = await fetch(url, { headers: { "User-Agent": "Filosofometro/1.0 (book covers)" } });
      if (res.ok) return (await res.json()).docs || [];
      process.stdout.write(`[${res.status}]`);
    } catch (e) { process.stdout.write("[erro]"); }
    await sleep(10000 * (tries + 1));
  }
  return [];
}
// A cover only when the title matches and the author matches; no "same author, different title" guess here,
// since a wrong cover is worse than the colored spine.
async function cover(title, author) {
  const m = title.match(/^(.*?)\s*\((.*)\)$/);
  const t = m ? m[1] : title, by = (m && !NOT_AUTHOR.test(m[2]) ? m[2] : author).replace(/^(com|with|con) /i, "");
  for (const q of [`${t} ${by}`, t]) {
    const docs = await search(q);
    await sleep(1200);
    const byWords = words(by);
    const hit = docs.find(d => d.cover_i && overlap(t, d.title) >= 0.75 && byWords.some(w => w.length > 3 && norm((d.author_name || []).join(" ")).includes(w)));
    if (hit) return { id: hit.cover_i, got: `${hit.title} | ${(hit.author_name || []).slice(0, 2).join(", ")}` };
  }
  return { id: 0, got: "" };
}

function listFor(lang) {
  if (lang === "pt") return [...DATA.PH, ...(DATA.BR || [])].map(p => ({ id: p.id, n: p.n, books: [p.b, ...(S.READING[p.id] || [])] }));
  const src = f => JSON.parse(fs.readFileSync(path.join(ROOT, "i18n", "src", f), "utf8"));
  const ph = { ...src(`${lang}-ph-a.json`), ...src(`${lang}-ph-b.json`) }, reg = src(`${lang}-regional.json`);
  return [
    ...DATA.PH.map(p => { const t = ph[p.id] || {}; return { id: p.id, n: t.n || p.n, books: [t.b || p.b, ...(t.reading || S.READING[p.id] || [])] }; }),
    ...reg.map(p => ({ id: p.id, n: p.n, books: [p.b, ...(p.reading || [])], regional: true })),
  ];
}

function write(pt, langs) {
  const js = `// Generated by tests/make-covers.js and tests/make-covers-lang.js. Open Library cover ids for each thinker's three books (0 = no cover).\n` +
    `// LANG holds the English and Spanish lists: a cover id, 0 for none, or null to reuse the Portuguese cover.\n(function(root){\n` +
    `const COVERS=${JSON.stringify(pt).replace(/\],"/g, '],\n"')};\n` +
    `const LANG=${JSON.stringify(langs).replace(/\],"/g, '],\n"')};\n` +
    `if(typeof module!=="undefined"){Object.defineProperty(COVERS,"lang",{value:LANG});module.exports=COVERS}else{root.AgoraCovers=COVERS;root.AgoraCoversLang=LANG}\n})(this);\n`;
  fs.writeFileSync(path.join(ROOT, "covers.js"), js);
}

(async () => {
  const lang = process.argv[2];
  if (!["pt", "en", "es"].includes(lang)) { console.log("Usage: node tests/make-covers-lang.js en|es|pt [keys]"); return; }
  const only = process.argv[3] ? new Set(process.argv[3].split(",")) : null;
  const pt = { ...OLD }, langs = JSON.parse(JSON.stringify(OLD.lang || { en: {}, es: {} }));
  const rows = [];
  for (const p of listFor(lang)) {
    const out = lang === "pt" ? pt[p.id] = (pt[p.id] || [0, 0, 0]).slice() : (langs[lang][p.id] = [null, null, null]);
    for (const [i, b] of p.books.entries()) {
      const key = `${p.id}/${i}`;
      if (only && !only.has(key)) continue;
      const r = await cover(b, p.n);
      // No cover of its own: the same work reuses the Portuguese cover; a different book gets none.
      out[i] = r.id || (lang === "pt" || p.regional || !(SAME[lang] || []).includes(key) ? 0 : null);
      rows.push(`| ${key} | ${b} | ${r.id || (out[i] === null ? "capa do PT" : "**sem capa**")} | ${r.got} |`);
      process.stdout.write(r.id ? "." : "x");
    }
  }
  // Re-read covers.js before writing, so runs for different languages at the same time keep each other's results.
  delete require.cache[require.resolve(path.join(ROOT, "covers.js"))];
  const cur = require(path.join(ROOT, "covers.js")), curLang = JSON.parse(JSON.stringify(cur.lang || { en: {}, es: {} }));
  if (lang === "pt") write({ ...cur, ...Object.fromEntries(Object.entries(pt).filter(([id]) => only ? [...only].some(k => k.startsWith(id + "/")) : true)) }, curLang);
  else { curLang[lang] = langs[lang]; write({ ...cur }, curLang); }
  const report = path.join(__dirname, `covers-report-${lang}.md`);
  fs.writeFileSync(report, `# Capas (${lang})\n\n| Livro | Título | Capa | Encontrado |\n|---|---|---|---|\n${rows.join("\n")}\n`);
  console.log(`\n${rows.filter(r => !/sem capa|capa do PT/.test(r)).length}/${rows.length} covers found, report in ${path.basename(report)}`);
})();
